const assert = require('node:assert/strict');
const { join } = require('node:path');
const accessibility = require('./ui-accessibility.cjs');
const { nativeReadingTools } = require('../test/ui/comparison-native-tools.cjs');

module.exports = async ({ win, nativeTheme, output, run, wait, click, key, shot }) => {
  const reports = [];
  const state = { scenario: 'critique-fixes', step: 'entry' }, native = nativeReadingTools(win, output, state, run);
  const paint = () => run('document.fonts.ready.then(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))');
  for (const [locale, theme] of [['zh-CN', 'light'], ['zh-TW', 'dark'], ['en', 'dark']]) {
    win.webContents.setZoomFactor(1); win.setContentSize(960, 680); nativeTheme.themeSource = theme;
    await win.loadFile(join(output, 'index.html'), { query: { locale } });
    await wait('!!document.querySelector(".archive-detail h1")');
    await click('.library-view-switch button:nth-child(2)'); await paint();
    const geometry = await run(`(() => {
      const pane=document.querySelector('.archive-detail-pane').getBoundingClientRect(), column=document.querySelector('.archive-compare-column').getBoundingClientRect();
      const paragraph=document.querySelector('.archive-compare-paragraph .markdown-preview p').getBoundingClientRect();
      return {contextOpen:document.querySelector('.archive-record-context').open,columnTop:column.top,paragraphBottom:paragraph.bottom,paneBottom:pane.bottom};
    })()`);
    assert.equal(geometry.contextOpen, false);
    assert.ok(geometry.columnTop < 430 && geometry.paragraphBottom <= geometry.paneBottom, 'a complete short paragraph is visible on comparison entry');
    const names = await run('({library:window.libraryTest.copy.archiveTitle,detail:window.libraryTest.copy.folderResults})');
    const tree = await accessibility(win);
    assert.equal(tree.filter(node => node.role === 'region' && node.name === names.library).length, 1);
    assert.equal(tree.filter(node => node.role === 'region' && node.name === names.detail).length, 1);
    assert.equal(tree.some(node => node.role === 'main'), false, 'the embedded detail does not introduce another main landmark');
    assert.equal(tree.some(node => node.role === 'heading' && node.level === 1), true, 'the compact question remains a first-level heading');
    await shot(`comparison-entry-${locale}-${theme}`);
    await click('.archive-record-context > summary');
    assert.equal(await run('document.querySelector(".archive-detail-heading").getClientRects().length>0'), true);
    await native.click('[data-archive-editor=synthesis]');
    await wait('!!document.querySelector(".synthesis-workspace")');
    await native.click('.synthesis-workspace .panel-close');
    await wait('document.querySelector(".archive-record-context")?.open && document.activeElement===document.querySelector("[data-archive-editor=synthesis]")');
    await native.click('.library-organize');
    await native.type('[name=archive-note]', 'Retain this unsaved context note.');
    await native.click('.archive-organization-close');
    await click('.archive-record-context > summary');
    await native.click('.library-view-switch button:first-child');
    await wait('!!document.querySelector(".confirm-dialog")');
    assert.equal(await run('document.querySelector(".confirm-dialog").checkVisibility()'), true, 'metadata confirmation escapes the closed context disclosure');
    await native.key('Escape');
    assert.equal(await run('document.querySelector(".archive-detail").dataset.view'), 'compare');
    assert.equal(await run('document.querySelector("[name=archive-note]").value'), 'Retain this unsaved context note.');
    await native.click('.library-metadata-actions button:last-child');
    await native.click('.archive-organization-close');
    await click('.comparison-manual-entry');
    const closed = await run('[...document.querySelectorAll("details.manual-category")].filter(node=>!node.open).length');
    assert.equal(closed, 8, 'empty category notes start collapsed');
    await shot(`manual-entry-${locale}-${theme}`);
    const opener = '.manual-comparison-source .answer-excerpt-open';
    await native.click(opener); await wait('!!document.querySelector("[name=answer-excerpt-original]")');
    await native.key('Escape');
    assert.equal(await run('document.activeElement===document.querySelector(".manual-comparison-source .answer-excerpt-open")'), true);
    await native.click(opener); await native.selectOriginalLine('[name=answer-excerpt-original]');
    await wait('!!document.querySelector(".excerpt-confirm-preview")');
    const selected = await run('document.querySelector(".excerpt-confirm-preview").textContent');
    assert.equal(await run('document.querySelector("[name=answer-excerpt-original]").value.split("\\n")[0]'), selected, 'native selection is the exact first saved line');
    await native.click('.folder-modal > button');
    await native.click('.manual-comparison-source .answer-excerpt-actions button:first-child');
    await wait('document.activeElement===document.querySelector("[name=comparison-excerpt-0]")');
    assert.equal(await run('document.querySelector("[name=comparison-excerpt-0]").value'), selected);
    await native.click('.manual-category > summary');
    await native.type('[name=comparison-note-conclusion-0]', 'An independent manual note.'); await paint();
    await click('.manual-category > summary');
    assert.equal(await run('document.querySelector("details.manual-category").open'), false);
    await click('.manual-category > summary');
    assert.equal(await run('document.querySelector("[name=comparison-note-conclusion-0]").value'), 'An independent manual note.');
    assert.equal(await run('window.libraryTest.writes'), 0);
    reports.push({ locale, theme, geometry, collapsedCategories: closed, exactExcerpt: true, focusReturned: true });
  }
  console.log('Critique fixes passed: three native comparison, excerpt, disclosure and accessibility groups.');
  return reports;
};
