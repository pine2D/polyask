export type ProxyCopy = { readonly [Key in keyof typeof PROXY_COPY.en]: string };

/** 代理 IPC 码与测试结果码 → 文案键。码是主进程产出的机器字面量（spec §5.3、§6.3），不在这里产码。 */
const RESULT_COPY: Readonly<Record<string, keyof ProxyCopy>> = {
  proxy_invalid: "proxyResultInvalid",
  proxy_busy: "proxyResultBusy",
  proxy_apply_failed: "proxyResultApplyFailed",
  proxy_secret_failed: "proxySavedSecretFailed",
  proxy_test_busy: "proxyResultTestBusy",
  proxy_not_pending: "proxyResultNotPending",
  proxy_pending_confirm: "proxySaveBlockedPending",
  proxy_failed: "proxyResultFailed",
  proxy_auth_failed: "proxyResultAuthFailed",
  network_error: "proxyResultNetwork",
  network_timeout: "proxyResultTimeout"
};

const FIELD_COPY: Readonly<Record<ProxyField | "password", keyof ProxyCopy>> = {
  host: "proxyErrorHost", port: "proxyErrorPort", bypass: "proxyErrorBypass",
  username: "proxyErrorUsername", password: "proxyErrorPassword", shape: "proxyErrorShape"
};

const MODE_COPY: Readonly<Record<ProxyMode, keyof ProxyCopy>> = {
  system: "proxyModeSystem", direct: "proxyModeDirect", custom: "proxyModeCustom"
};

/** 协议名是通用技术名词，三语一致。 */
export const PROXY_SCHEME_LABELS: Readonly<Record<ProxyScheme, string>> = {
  http: "HTTP", https: "HTTPS", socks4: "SOCKS4", socks5: "SOCKS5"
};

/** 未知或缺失的码一律落到通用失败文案，绝不把机器码直接展示给用户。 */
export function describeProxyResult(copy: ProxyCopy, code: string | null): string {
  const key = code !== null && Object.hasOwn(RESULT_COPY, code) ? RESULT_COPY[code] : "proxyResultUnknown";
  return copy[key];
}

export function describeProxyField(copy: ProxyCopy, field: ProxyField | "password"): string {
  return copy[FIELD_COPY[field]];
}

export function proxyModeLabel(copy: ProxyCopy, mode: ProxyMode): string {
  return copy[MODE_COPY[mode]];
}
